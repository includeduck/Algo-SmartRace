"""Charts and markdown tables for the report, from smartrace_bench's CSVs.

Report-only helper (Python 3 + matplotlib), NOT part of the game or its
build -- acknowledge matplotlib in the report. Reads results/summary/*.csv,
writes results/charts/*.png and results/RESULTS.md.

    python tools/plot_results.py [results-dir]
"""
import csv
import math
import os
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = sys.argv[1] if len(sys.argv) > 1 else "results"
SUMMARY = os.path.join(ROOT, "summary")
CHARTS = os.path.join(ROOT, "charts")
os.makedirs(CHARTS, exist_ok=True)


def load(name):
    with open(os.path.join(SUMMARY, name), newline="") as f:
        return list(csv.DictReader(f))


def num(row, key):
    return float(row[key])


def save(fig, name):
    fig.tight_layout()
    fig.savefig(os.path.join(CHARTS, name), dpi=140)
    plt.close(fig)


md = ["# Experiment results", "",
      "Generated by `tools/plot_results.py` from `results/summary/*.csv` "
      "(raw samples in `results/raw/`). Times are medians of the timed runs, in microseconds.", ""]

hw_path = os.path.join(ROOT, "hardware.txt")
if os.path.exists(hw_path):
    md += ["## Hardware", "", "```"] + open(hw_path).read().strip().splitlines() + ["```", ""]

env_path = os.path.join(SUMMARY, "environment.txt")
if os.path.exists(env_path):
    md += ["## Environment", "", "```"] + open(env_path).read().strip().splitlines() + ["```", ""]

# ---------------------------------------------------------------- Exp 1
rows = load("exp1_bfs_dfs_summary.csv")
fig, axes = plt.subplots(1, 2, figsize=(11, 4.2))
for ax, density in zip(axes, ["sparse_deg3", "dense_deg12"]):
    for algo in ["BFS", "DFS_traversal", "DFS_components", "DFS_cycles"]:
        pts = [(num(r, "V") + num(r, "E"), num(r, "median_us")) for r in rows
               if r["algo"] == algo and r["density"] == density]
        pts.sort()
        ax.loglog([p[0] for p in pts], [p[1] for p in pts], marker="o", label=algo)
    ax.set_title(f"Exp 1: {density}")
    ax.set_xlabel("V + E")
    ax.set_ylabel("median time (us)")
    ax.grid(True, which="both", alpha=0.3)
    ax.legend(fontsize=8)
save(fig, "exp1_time_vs_size.png")

fig, ax = plt.subplots(figsize=(6.5, 4.2))
for algo in ["BFS", "DFS_traversal", "DFS_components"]:
    for density, style in [("sparse_deg3", "-"), ("dense_deg12", "--")]:
        pts = sorted((num(r, "V"), 1000.0 * num(r, "median_us") / (num(r, "V") + num(r, "E")))
                     for r in rows if r["algo"] == algo and r["density"] == density)
        ax.semilogx([p[0] for p in pts], [p[1] for p in pts], style, marker="o", label=f"{algo} {density}")
ax.set_title("Exp 1: time per (V+E) element")
ax.set_xlabel("V")
ax.set_ylabel("ns per (V + E)")
ax.grid(True, which="both", alpha=0.3)
ax.legend(fontsize=7)
save(fig, "exp1_normalised.png")

md += ["## Experiment 1 -- BFS and DFS", "",
       "| algo | density | V | E | median us | ns/(V+E) | visited | edges examined |", "|---|---|---|---|---|---|---|---|"]
for r in rows:
    md.append(f"| {r['algo']} | {r['density']} | {r['V']} | {r['E']} | {num(r, 'median_us'):.1f} | "
              f"{1000 * num(r, 'median_us') / (num(r, 'V') + num(r, 'E')):.2f} | {r['visited']} | {r['edges_examined']} |")
md.append("")

# ---------------------------------------------------------------- Exp 2
rows = load("exp2_routing_summary.csv")
search = [r for r in rows if r["algo"] in ("Dijkstra", "AStar")]
presets = ["Balanced", "Speed", "Economy", "Safety", "Distance"]

fig, axes = plt.subplots(1, 2, figsize=(11, 4.2))
for ax, metric, label in [(axes[0], "expanded", "expanded vertices"), (axes[1], "median_us", "median time (us)")]:
    for algo, style in [("Dijkstra", "-"), ("AStar", "--")]:
        for preset in ["Balanced", "Distance"]:
            pts = sorted((num(r, "V"), num(r, metric)) for r in search
                         if r["algo"] == algo and r["preset"] == preset and r["graph"].startswith("grid")
                         and r["query"] == "far_corner_to_corner")
            ax.loglog([p[0] for p in pts], [p[1] for p in pts], style, marker="o", label=f"{algo} {preset}")
    ax.set_title(f"Exp 2: grid, corner to corner -- {label}")
    ax.set_xlabel("V")
    ax.grid(True, which="both", alpha=0.3)
    ax.legend(fontsize=8)
save(fig, "exp2_grid_scaling.png")

biggest = max(num(r, "V") for r in search if r["graph"].startswith("grid"))
fig, ax = plt.subplots(figsize=(8, 4.2))
width = 0.38
for i, (algo, colour) in enumerate([("Dijkstra", "tab:blue"), ("AStar", "tab:orange")]):
    vals = []
    for preset in presets:
        match = [r for r in search if r["algo"] == algo and r["preset"] == preset and num(r, "V") == biggest
                 and r["query"] == "far_corner_to_corner"]
        vals.append(num(match[0], "expanded") if match else 0)
    ax.bar([x + (i - 0.5) * width for x in range(len(presets))], vals, width, label=algo, color=colour)
ax.set_xticks(range(len(presets)))
ax.set_xticklabels(presets)
ax.set_ylabel("expanded vertices")
ax.set_title(f"Exp 2: expanded vertices by preset (grid V={int(biggest)}, corner to corner)")
ax.legend()
save(fig, "exp2_expanded_by_preset.png")

md += ["## Experiment 2 -- Dijkstra and A*", "",
       "| graph | query | preset | V | Dijkstra us | A* us | Dijkstra expanded | A* expanded | Dijkstra heap ops | A* heap ops | cost (both) | h scale |",
       "|---|---|---|---|---|---|---|---|---|---|---|---|"]
for d in [r for r in search if r["algo"] == "Dijkstra"]:
    a = [r for r in search if r["algo"] == "AStar" and r["graph"] == d["graph"] and r["query"] == d["query"]
         and r["preset"] == d["preset"]][0]
    md.append(f"| {d['graph']} | {d['query']} | {d['preset']} | {d['V']} | {num(d, 'median_us'):.1f} | "
              f"{num(a, 'median_us'):.1f} | {d['expanded']} | {a['expanded']} | {d['heap_ops']} | {a['heap_ops']} | "
              f"{num(d, 'path_cost'):.4f} | {num(a, 'heuristic_scale'):.5f} |")
md.append("")

# ---------------------------------------------------------------- Exp 3
rows = load("exp3_knapsack_summary.csv")
fig, axes = plt.subplots(1, 2, figsize=(11, 4.2))
for algo, style in [("DP_table", "-"), ("DP_value_only", "--")]:
    pts = sorted((num(r, "m") * num(r, "budget"), num(r, "median_us")) for r in rows
                 if r["algo"] == algo and r["distribution"] == "uncorrelated")
    axes[0].loglog([p[0] for p in pts], [p[1] for p in pts], style, marker="o", label=algo)
pts = sorted((num(r, "m"), num(r, "median_us")) for r in rows if r["algo"] == "Greedy" and r["distribution"] == "uncorrelated")
axes[0].loglog([p[0] for p in pts], [p[1] for p in pts], ":", marker="s", label="Greedy (x = m)")
axes[0].set_xlabel("m x B (DP) / m (greedy)")
axes[0].set_ylabel("median time (us)")
axes[0].set_title("Exp 3: DP time vs table size")
axes[0].grid(True, which="both", alpha=0.3)
axes[0].legend(fontsize=8)
for budget in ["50", "500", "5000"]:
    pts = sorted((num(r, "m"), num(r, "median_us")) for r in rows
                 if r["algo"] == "Exhaustive" and r["budget"] == budget and r["distribution"] == "uncorrelated")
    axes[1].semilogy([p[0] for p in pts], [p[1] for p in pts], marker="o", label=f"Exhaustive B={budget}")
axes[1].set_xlabel("m (items)")
axes[1].set_ylabel("median time (us)")
axes[1].set_title("Exp 3: exhaustive search is exponential in m")
axes[1].grid(True, which="both", alpha=0.3)
axes[1].legend(fontsize=8)
save(fig, "exp3_time.png")

quality = load("exp3_greedy_quality.csv")
fig, ax = plt.subplots(figsize=(8, 4.2))
for dist, style in [("uncorrelated", "-"), ("correlated", "--")]:
    for budget in ["50", "500", "5000"]:
        pts = sorted((num(r, "m"), num(r, "mean_greedy_over_dp")) for r in quality
                     if r["distribution"] == dist and r["budget"] == budget)
        ax.semilogx([p[0] for p in pts], [p[1] for p in pts], style, marker="o", label=f"{dist} B={budget}")
ax.set_xlabel("m (items)")
ax.set_ylabel("mean greedy benefit / DP benefit")
ax.set_title("Exp 3: greedy quality (50 instances per point)")
ax.grid(True, which="both", alpha=0.3)
ax.legend(fontsize=7)
save(fig, "exp3_greedy_quality.png")

md += ["## Experiment 3 -- DP and Greedy", "", "### Named cases", "",
       "| case | items | budget | DP benefit (items) | greedy benefit (items) | exhaustive | greedy strictly worse |",
       "|---|---|---|---|---|---|---|"]
for r in load("exp3_cases.csv"):
    md.append(f"| {r['case']} | {r['items']} | {r['budget']} | {r['dp_benefit']} ({r['dp_items']}) | "
              f"{r['greedy_benefit']} ({r['greedy_items']}) | {r['exhaustive_benefit']} | {r['greedy_strictly_worse']} |")
md += ["", "### Timings", "",
       "| algo | distribution | m | B | median us | benefit | selected | DP states |", "|---|---|---|---|---|---|---|---|"]
for r in rows:
    md.append(f"| {r['algo']} | {r['distribution']} | {r['m']} | {r['budget']} | {num(r, 'median_us'):.2f} | "
              f"{r['benefit']} | {r['selected_items']} | {r['dp_states']} |")
md += ["", "### Greedy quality", "",
       "| distribution | m | B | greedy strictly worse (of 50) | mean greedy/DP | worst greedy/DP |", "|---|---|---|---|---|---|"]
for r in quality:
    md.append(f"| {r['distribution']} | {r['m']} | {r['budget']} | {r['greedy_strictly_worse']} | "
              f"{num(r, 'mean_greedy_over_dp'):.4f} | {num(r, 'worst_greedy_over_dp'):.4f} |")
md.append("")

# ---------------------------------------------------------------- Exp 4
rows = load("exp4_event_queue_summary.csv")
fig, axes = plt.subplots(1, 2, figsize=(11, 4.2))
for ax, phase in zip(axes, ["insert", "extract"]):
    for workload in ["random", "tie_heavy", "cancel_heavy", "with_expiry"]:
        pts = sorted((num(r, "n"), num(r, "ns_per_operation")) for r in rows
                     if r["phase"] == phase and r["workload"] == workload)
        ax.semilogx([p[0] for p in pts], [p[1] for p in pts], marker="o", label=workload)
    ax.set_title(f"Exp 4: {phase}, ns per operation")
    ax.set_xlabel("n events")
    ax.set_ylabel("ns / operation")
    ax.grid(True, which="both", alpha=0.3)
    ax.legend(fontsize=8)
save(fig, "exp4_ns_per_op.png")

fig, ax = plt.subplots(figsize=(6.5, 4.2))
for workload in ["random", "tie_heavy", "cancel_heavy", "with_expiry"]:
    pts = sorted((num(r, "n"), (num(r, "heap_comparisons") + num(r, "heap_swaps")) / num(r, "operations") / math.log2(num(r, "n")))
                 for r in rows if r["phase"] == "extract" and r["workload"] == workload)
    ax.semilogx([p[0] for p in pts], [p[1] for p in pts], marker="o", label=workload)
ax.set_title("Exp 4: extract heap operations / (pops x log2 n)")
ax.set_xlabel("n events")
ax.grid(True, which="both", alpha=0.3)
ax.legend(fontsize=8)
save(fig, "exp4_heap_ops.png")

md += ["## Experiment 4 -- Event priority queue", "",
       "| phase | workload | n | median us | ns/op | operations | heap comparisons | heap swaps | delivered | cancelled skipped |",
       "|---|---|---|---|---|---|---|---|---|---|"]
for r in rows:
    md.append(f"| {r['phase']} | {r['workload']} | {r['n']} | {num(r, 'median_us'):.1f} | {r['ns_per_operation']} | "
              f"{r['operations']} | {r['heap_comparisons']} | {r['heap_swaps']} | {r['delivered']} | {r['cancelled_skipped']} |")
md.append("")

# ---------------------------------------------------------------- Exp 5
rows = load("exp5_sorting_summary.csv")
fig, axes = plt.subplots(1, 4, figsize=(15, 3.8), sharey=True)
for ax, inp in zip(axes, ["random", "sorted", "reverse", "duplicate"]):
    for algo in ["MergeSort", "QuickSort", "HeapSort"]:
        pts = sorted((num(r, "n"), num(r, "median_us")) for r in rows if r["algo"] == algo and r["input"] == inp)
        ax.loglog([p[0] for p in pts], [p[1] for p in pts], marker="o", label=algo)
    ax.set_title(f"Exp 5: {inp}")
    ax.set_xlabel("n")
    ax.grid(True, which="both", alpha=0.3)
axes[0].set_ylabel("median time (us)")
axes[0].legend(fontsize=8)
save(fig, "exp5_sort_time.png")

fig, ax = plt.subplots(figsize=(7, 4.2))
for algo, style in [("MergeSort", "-"), ("QuickSort", "--"), ("HeapSort", ":")]:
    for inp in ["random", "sorted", "duplicate"]:
        pts = sorted((num(r, "n"), num(r, "comparisons") / (num(r, "n") * math.log2(num(r, "n")))) for r in rows
                     if r["algo"] == algo and r["input"] == inp)
        ax.semilogx([p[0] for p in pts], [p[1] for p in pts], style, marker="o", label=f"{algo} {inp}")
ax.set_title("Exp 5: comparisons / (n log2 n)")
ax.set_xlabel("n")
ax.grid(True, which="both", alpha=0.3)
ax.legend(fontsize=7)
save(fig, "exp5_comparisons.png")

topk = load("exp5_topk_summary.csv")
fig, axes = plt.subplots(1, 2, figsize=(11, 4.2))
for ax, metric, label in [(axes[0], "comparisons", "comparisons"), (axes[1], "median_us", "median time (us)")]:
    for n in sorted({r["n"] for r in topk}, key=int):
        full = [r for r in topk if r["algo"] == "MergeSort_full" and r["n"] == n][0]
        for algo, style in [("TopK_size_k_heap", "-"), ("TopK_heapify_extract", "--")]:
            pts = sorted((num(r, "k") / num(r, "n"), num(r, metric) / num(full, metric)) for r in topk
                         if r["algo"] == algo and r["n"] == n)
            ax.semilogx([max(p[0], 1e-6) for p in pts], [p[1] for p in pts], style, marker="o", label=f"{algo} n={n}")
    ax.axhline(1.0, color="grey", linewidth=1)
    ax.set_title(f"Exp 5: top-k {label} relative to a full Merge Sort")
    ax.set_xlabel("k / n")
    ax.grid(True, which="both", alpha=0.3)
    ax.legend(fontsize=7)
save(fig, "exp5_topk.png")

md += ["## Experiment 5 -- Sorting and top-k", "",
       "| algo | input | n | median us | comparisons | swaps/moves |", "|---|---|---|---|---|---|"]
for r in rows:
    md.append(f"| {r['algo']} | {r['input']} | {r['n']} | {num(r, 'median_us'):.2f} | {r['comparisons']} | {r['swaps_or_moves']} |")
md += ["", "| top-k algo | n | k | median us | comparisons |", "|---|---|---|---|---|"]
for r in topk:
    md.append(f"| {r['algo']} | {r['n']} | {r['k']} | {num(r, 'median_us'):.1f} | {r['comparisons']} |")
md.append("")

# ---------------------------------------------------------------- Correctness
checks = load("correctness.csv")
failed = [c for c in checks if c["passed"] != "yes"]
md += ["## Correctness checks (untimed)", "",
       f"{len(checks)} checks, {len(failed)} failed. Full list: `results/summary/correctness.csv`.", ""]
for c in failed:
    md.append(f"- FAILED {c['experiment']} {c['check']}: {c['detail']}")
md += ["", "## Charts", ""]
for name in sorted(os.listdir(CHARTS)):
    md.append(f"![{name}](charts/{name})")

with open(os.path.join(ROOT, "RESULTS.md"), "w", encoding="utf-8") as f:
    f.write("\n".join(md) + "\n")
print(f"wrote {CHARTS} and {os.path.join(ROOT, 'RESULTS.md')}")
