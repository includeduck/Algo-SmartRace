"""Authoring aid for data/circuits/*.trk -- NOT part of the game or its build.

Generates the three hand-designed circuits with exact geometry: every
edge's distance is the Euclidean distance between its endpoints, which is
what keeps the A* heuristic admissible (see src/algo/AStar.h). It then
validates each circuit and writes the .trk files. Run from the repo root:

    python tools/gen_circuits.py

Design rules every circuit follows:
  - 10 ordered checkpoints, a Start and a Finish, at least one cycle and
    one dead end;
  - at least 2 shortcuts, each bypassing ONLY plain intersections, so
    taking one never skips a mandatory checkpoint;
  - fuel stations and nitro pickups sit just off the main loop, joined to
    two neighbouring loop vertices, so a detour costs about a second;
  - fuel is tuned so a full tank lasts roughly two laps: a 3-lap race
    needs one refuelling stop;
  - MAINROUTE (Opponent 1's fixed lap) is a REAL closed loop: every
    consecutive pair, and the wrap-around, is an actual edge.
"""
import math
import os

SPEED = 42.0        # world units per second at base difficulty
FUEL_RATE = 0.02    # fuel units per world unit of distance
STATION_OFFSET = 60.0


def dist(a, b):
    return math.hypot(a[0] - b[0], a[1] - b[1])


def polar(cx, cy, r, degrees):
    rad = math.radians(degrees)
    return (cx + r * math.cos(rad), cy + r * math.sin(rad))


class Circuit:
    def __init__(self, num, name, laps=3):
        self.num = num
        self.name = name
        self.laps = laps
        self.vertices = []   # (x, y, type, cpOrder)
        self.edges = []      # (from, to, distance, baseTime, fuelCost, difficulty, shortcut, directed)
        self.main_route = []
        self.detours = []    # (blockedEdgeId, [vertices from..to])
        self.shortcuts_pref = []
        self.events = []     # (timeMs, type, target, durationMs)

    def add_vertex(self, x, y, vtype, cp=-1):
        self.vertices.append((x, y, vtype, cp))
        return len(self.vertices) - 1

    def add_labelled(self, x, y, label):
        if label == 'Start':
            return self.add_vertex(x, y, 'Start')
        if label == 'Finish':
            return self.add_vertex(x, y, 'Finish')
        if label.startswith('CP'):
            return self.add_vertex(x, y, 'Checkpoint', int(label[2:]))
        return self.add_vertex(x, y, 'Intersection')

    def add_edge(self, a, b, difficulty, shortcut=False, directed=False):
        d = dist(self.vertices[a][:2], self.vertices[b][:2])
        self.edges.append((a, b, d, d / SPEED, d * FUEL_RATE, difficulty, shortcut, directed))
        return len(self.edges) - 1

    def add_service_between(self, a, b, vtype, center, offset=STATION_OFFSET):
        """A service vertex just outside the loop edge a-b, joined to both."""
        ax, ay = self.vertices[a][:2]
        bx, by = self.vertices[b][:2]
        mx, my = (ax + bx) / 2.0, (ay + by) / 2.0
        dx, dy = mx - center[0], my - center[1]
        length = math.hypot(dx, dy) or 1.0
        v = self.add_vertex(mx + dx / length * offset, my + dy / length * offset, vtype)
        self.add_edge(v, a, 1)
        self.add_edge(v, b, 1)
        return v

    def add_spur(self, parent, vtype, center, length=85.0):
        """A dead-end spur pointing away from `center`."""
        px, py = self.vertices[parent][:2]
        dx, dy = px - center[0], py - center[1]
        norm = math.hypot(dx, dy) or 1.0
        v = self.add_vertex(px + dx / norm * length, py + dy / norm * length, vtype)
        self.add_edge(v, parent, 2)
        return v

    def render(self):
        out = [f'CIRCUIT {self.num} "{self.name}"', f'LAPS {self.laps}', '',
               '# Generated by tools/gen_circuits.py -- edit the script, not this file.', '',
               '# VERTEX id x y type [cpOrder]']
        for i, (x, y, vtype, cp) in enumerate(self.vertices):
            suffix = f' {cp}' if cp >= 0 else ''
            out.append(f'VERTEX {i} {x:.1f} {y:.1f} {vtype}{suffix}')
        out += ['', '# EDGE id from to distance baseTime fuelCost difficulty shortcut directed']
        for i, (a, b, d, t, f, diff, sc, dirx) in enumerate(self.edges):
            out.append(f'EDGE {i} {a} {b} {d:.2f} {t:.2f} {f:.2f} {diff} {int(sc)} {int(dirx)}')
        out += ['', '# Opponent 1: fixed main route (one closed lap)',
                'MAINROUTE ' + ' '.join(str(v) for v in self.main_route)]
        for edge, via in self.detours:
            out.append(f'DETOUR {edge} ' + ' '.join(str(v) for v in via))
        out += ['', '# Opponent 2: preferred shortcuts']
        out += [f'SHORTCUT {e}' for e in self.shortcuts_pref]
        out += ['', '# Scripted events: triggerTimeMs Type target durationMs']
        out += [f'EVENT {t} {typ} {target} {dur}' for (t, typ, target, dur) in self.events]
        out.append('')
        return '\n'.join(out)


# ---------------------------------------------------------------------------
# C1 -- Harbor Loop: a 16-vertex ring. 12 of the positions are Start,
# CP1..CP10 and Finish; the other 4 are plain intersections pushed outward
# into two "bulges", and each shortcut is a chord across one bulge.
# ---------------------------------------------------------------------------
def build_harbor():
    c = Circuit(1, 'Harbor Loop')
    center = (450.0, 420.0)
    labels = ['Start', 'CP1', 'CP2', 'I', 'I', 'CP3', 'CP4', 'CP5',
              'CP6', 'I', 'I', 'CP7', 'CP8', 'CP9', 'CP10', 'Finish']
    ring = []
    for i, label in enumerate(labels):
        radius = 380.0 if label == 'I' else 300.0
        x, y = polar(center[0], center[1], radius, 360.0 * i / len(labels))
        ring.append(c.add_labelled(x, y, label))
    for i in range(len(ring)):
        c.add_edge(ring[i], ring[(i + 1) % len(ring)], 2 if i % 4 == 0 else 1)

    sc1 = c.add_edge(ring[2], ring[5], 5, shortcut=True)    # CP2 -> CP3 across a bulge
    sc2 = c.add_edge(ring[8], ring[11], 4, shortcut=True)   # CP6 -> CP7 across a bulge

    inner = c.add_vertex(center[0], center[1], 'Intersection')
    c.add_edge(inner, ring[1], 2)
    c.add_edge(inner, ring[7], 2)
    dead = c.add_vertex(center[0] + 60.0, center[1] + 60.0, 'DeadEnd')
    c.add_edge(dead, inner, 2)

    nitro1 = c.add_service_between(ring[0], ring[1], 'NitroPickup', center)
    c.add_service_between(ring[5], ring[6], 'FuelStation', center)
    c.add_service_between(ring[12], ring[13], 'NitroPickup', center)
    c.add_service_between(ring[13], ring[14], 'FuelStation', center)

    c.main_route = ring[:]                                   # closes via Finish -> Start
    c.detours.append((0, [ring[0], nitro1, ring[1]]))        # around the Start -> CP1 road
    c.shortcuts_pref = [sc1, sc2]
    c.events = [(15000, 'OilSpill', 3, 20000), (40000, 'RoadBlock', 0, 0),
                (55000, 'RoadClear', 0, 0), (70000, 'NitroBooster', nitro1, 25000)]
    return c


# ---------------------------------------------------------------------------
# C2 -- Twin Peaks: two 10-vertex lobes facing each other, joined by an
# undirected bridge and a ONE-WAY mountain pass (A -> B only). While the
# bridge is closed, a racer in lobe B cannot get back to lobe A: the
# designed "wait for the road to reopen" scenario.
# ---------------------------------------------------------------------------
def build_twin_peaks():
    c = Circuit(2, 'Twin Peaks')
    a_center, b_center = (250.0, 400.0), (720.0, 400.0)
    a_labels = ['Start', 'CP1', 'CP2', 'I', 'I', 'CP3', 'CP4', 'CP5', 'I', 'I']
    b_labels = ['CP6', 'CP7', 'I', 'I', 'CP8', 'CP9', 'CP10', 'Finish', 'I', 'I']

    def lobe(center, labels, start_deg, step_deg):
        ids = []
        for i, label in enumerate(labels):
            # Indices 8 and 9 are the bridge/pass vertices facing the other
            # lobe; the two mid-lobe intersections bulge outward.
            radius = 220.0 if (label == 'I' and i < 8) else 170.0
            x, y = polar(center[0], center[1], radius, start_deg + step_deg * i)
            ids.append(c.add_labelled(x, y, label))
        for i in range(len(ids)):
            c.add_edge(ids[i], ids[(i + 1) % len(ids)], 2 if i % 3 == 0 else 1)
        return ids

    A = lobe(a_center, a_labels, 54.0, 36.0)     # A[8], A[9] face right
    B = lobe(b_center, b_labels, 126.0, -36.0)   # B[8], B[9] face left

    bridge = c.add_edge(A[8], B[8], 3)
    c.add_edge(A[9], B[9], 3, directed=True)     # the one-way mountain pass
    sc_a = c.add_edge(A[2], A[5], 5, shortcut=True)   # CP2 -> CP3
    sc_b = c.add_edge(B[1], B[4], 5, shortcut=True)   # CP7 -> CP8

    c.add_service_between(A[6], A[7], 'FuelStation', a_center)
    fuel_b = c.add_service_between(B[5], B[6], 'FuelStation', b_center)
    c.add_service_between(A[0], A[1], 'NitroPickup', a_center)
    c.add_service_between(B[2], B[3], 'NitroPickup', b_center)
    c.add_spur(A[3], 'DeadEnd', a_center)
    c.add_spur(B[2], 'DeadEnd', b_center)

    c.main_route = A[0:9] + [B[8], B[9]] + B[0:8] + [B[8], A[8], A[9], A[0]]
    c.detours.append((bridge, [A[8], A[9], B[9], B[8]]))   # A -> B over the pass
    c.shortcuts_pref = [sc_a, sc_b]
    c.events = [(20000, 'SpeedRestriction', bridge, 15000), (35000, 'FuelStationToggle', fuel_b, 30000),
                (50000, 'RoadBlock', bridge, 0), (70000, 'RoadClear', bridge, 0)]
    return c


# ---------------------------------------------------------------------------
# C3 -- Downtown: a 5x4 street grid. The checkpoint sequence loops around
# the grid and back to Start; two diagonal "avenues" are the shortcuts --
# short but difficulty 5 -- so Speed, Economy and Safety can disagree.
# ---------------------------------------------------------------------------
def build_downtown():
    c = Circuit(3, 'Downtown')
    cols, rows, spacing = 5, 4, 130.0
    cells = {
        (0, 0): 'Start', (1, 1): 'CP1', (0, 2): 'CP2', (0, 3): 'CP3', (0, 4): 'CP4',
        (1, 4): 'CP5', (2, 4): 'CP6', (3, 3): 'CP7', (3, 2): 'CP8', (2, 1): 'CP9',
        (3, 0): 'CP10', (2, 0): 'Finish',
        (1, 3): 'FuelStation', (3, 1): 'FuelStation', (2, 2): 'NitroPickup', (3, 4): 'NitroPickup',
    }
    grid = {}
    for r in range(rows):
        for col in range(cols):
            x, y = 100.0 + col * spacing, 100.0 + r * spacing
            label = cells.get((r, col), 'I')
            if label in ('FuelStation', 'NitroPickup'):
                grid[(r, col)] = c.add_vertex(x, y, label)
            else:
                grid[(r, col)] = c.add_labelled(x, y, label)

    for r in range(rows):
        for col in range(cols - 1):
            c.add_edge(grid[(r, col)], grid[(r, col + 1)], 2 if col % 2 else 1)
    for col in range(cols):
        for r in range(rows - 1):
            c.add_edge(grid[(r, col)], grid[(r + 1, col)], 1 if r % 2 else 2)

    diag1 = c.add_edge(grid[(0, 0)], grid[(1, 1)], 5, shortcut=True)   # Start -> CP1
    diag2 = c.add_edge(grid[(2, 4)], grid[(3, 3)], 5, shortcut=True)   # CP6 -> CP7

    dead = c.add_vertex(100.0 + 2 * spacing, 10.0, 'DeadEnd')          # spur above CP2
    c.add_edge(dead, grid[(0, 2)], 2)

    path = [(0, 0), (0, 1), (1, 1), (1, 2), (0, 2), (0, 3), (0, 4), (1, 4), (2, 4), (2, 3),
            (3, 3), (3, 2), (2, 2), (2, 1), (3, 1), (3, 0), (2, 0), (1, 0)]
    c.main_route = [grid[p] for p in path]                             # (1,0) -> (0,0) closes it
    c.detours.append((0, [grid[(0, 0)], grid[(1, 0)], grid[(1, 1)], grid[(0, 1)]]))
    c.shortcuts_pref = [diag1, diag2]
    c.events = [(10000, 'OilSpill', diag1, 20000), (45000, 'RoadBlock', 0, 0),
                (65000, 'RoadClear', 0, 0)]
    return c


def validate(circuit):
    problems = []
    adjacency = {}
    for (a, b, *_rest, directed) in circuit.edges:
        adjacency.setdefault(a, set()).add(b)
        if not directed:
            adjacency.setdefault(b, set()).add(a)

    route = circuit.main_route
    for i in range(len(route) - 1):
        if route[i + 1] not in adjacency.get(route[i], set()):
            problems.append(f'MAINROUTE step {i}: no edge {route[i]} -> {route[i + 1]}')
    if route[-1] != route[0] and route[0] not in adjacency.get(route[-1], set()):
        problems.append(f'MAINROUTE does not close: no edge {route[-1]} -> {route[0]}')

    for edge, via in circuit.detours:
        a, b = circuit.edges[edge][0], circuit.edges[edge][1]
        if via[0] != a or via[-1] != b:
            problems.append(f'DETOUR {edge} must run from {a} to {b}')
        for i in range(len(via) - 1):
            if via[i + 1] not in adjacency.get(via[i], set()):
                problems.append(f'DETOUR {edge}: no edge {via[i]} -> {via[i + 1]}')

    checkpoints = sorted(v[3] for v in circuit.vertices if v[3] >= 0)
    if checkpoints != list(range(1, 11)):
        problems.append(f'checkpoints are {checkpoints}, expected 1..10')
    if sum(1 for e in circuit.edges if e[6]) < 2:
        problems.append('fewer than 2 shortcuts')
    return problems


def summary(circuit):
    count = lambda t: sum(1 for v in circuit.vertices if v[2] == t)
    return (f'{circuit.name}: V={len(circuit.vertices)} E={len(circuit.edges)} '
            f'shortcuts={sum(1 for e in circuit.edges if e[6])} fuel={count("FuelStation")} '
            f'nitro={count("NitroPickup")} deadEnds={count("DeadEnd")}')


def main():
    out_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'data', 'circuits')
    circuits = [(build_harbor(), 'c1_harbor.trk'), (build_twin_peaks(), 'c2_twinpeaks.trk'),
                (build_downtown(), 'c3_downtown.trk')]

    failed = False
    for circuit, _ in circuits:
        print(summary(circuit))
        for problem in validate(circuit):
            print('  INVALID:', problem)
            failed = True
    if failed:
        raise SystemExit('validation failed -- no files written')

    for circuit, name in circuits:
        path = os.path.normpath(os.path.join(out_dir, name))
        with open(path, 'w', newline='\n') as f:
            f.write(circuit.render())
        print('wrote', path)


if __name__ == '__main__':
    main()
